"""Regenerates sql/database.sql (MySQL schema + sample data) from the SQLAlchemy models.

    python tools/build_sql.py

You normally do NOT need to run this; sql/database.sql is already included.
"""
import os
import sys
import tempfile
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
tmp = Path(tempfile.mkdtemp())
os.environ["DATABASE_URL"] = f"sqlite:///{tmp / 'build.db'}"
os.environ["UPLOAD_DIR"] = str(ROOT / "uploads")

from sqlalchemy.dialects import mysql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from database.connection import SessionLocal, engine  # noqa: E402
from database.models import Base  # noqa: E402
from services import file_service  # noqa: E402
from services.seed_data import seed  # noqa: E402

Base.metadata.create_all(engine)
with SessionLocal() as db:
    seed(db, file_service.UPLOAD_DIR)


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, datetime):
        return f"'{v:%Y-%m-%d %H:%M:%S}'"
    if isinstance(v, date):
        return f"'{v:%Y-%m-%d}'"
    s = str(v).replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r")
    return f"'{s}'"


d = mysql.dialect()
out = ["-- JobPortal database for MySQL / MariaDB (generated by tools/build_sql.py)",
       "-- Import in MySQL Workbench: File > Open SQL Script > run (lightning icon).",
       "-- WARNING: this script DROPS and re-creates the tables.",
       "-- Sample logins: password for every account is  Password@123", "",
       "CREATE DATABASE IF NOT EXISTS job_portal CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
       "USE job_portal;", "SET FOREIGN_KEY_CHECKS = 0;", ""]
tables = Base.metadata.sorted_tables
for t in reversed(tables):
    out.append(f"DROP TABLE IF EXISTS `{t.name}`;")
out.append("")
for t in tables:
    out.append(str(CreateTable(t).compile(dialect=d)).strip() + ";")
    for ix in sorted(t.indexes, key=lambda i: i.name):
        out.append(str(CreateIndex(ix).compile(dialect=d)).strip() + ";")
    out.append("")
with engine.connect() as conn:
    for t in tables:
        rows = conn.execute(t.select().order_by(t.c.id)).fetchall()
        if not rows:
            continue
        cols = ", ".join(f"`{c.name}`" for c in t.columns)
        out.append(f"-- {t.name}: {len(rows)} rows")
        out.append(f"INSERT INTO `{t.name}` ({cols}) VALUES")
        out.append(",\n".join("  (" + ", ".join(lit(v) for v in r) + ")" for r in rows) + ";")
        out.append("")
out.append("SET FOREIGN_KEY_CHECKS = 1;")
(ROOT / "sql").mkdir(exist_ok=True)
(ROOT / "sql" / "database.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print("Wrote sql/database.sql")
